    fun localizeClass(classLevel: String): String {
        if (language == AppLanguage.EN) return classLevel
        return when (classLevel.trim()) {
            "Pre-Primary" -> "প্রাক-প্রাথমিক"
            "Class 1" -> "১ম শ্রেণি"
            "Class 2" -> "২য় শ্রেণি"
            "Class 3" -> "৩য় শ্রেণি"
            "Class 4" -> "৪র্থ শ্রেণি"
            "Class 5" -> "৫ম শ্রেণি"
            "All Classes" -> "সকল শ্রেণি"
            else -> classLevel
        }
    }

    fun localizeExamTitle(exam: ExamTermConfig): String {
        if (language == AppLanguage.EN) return exam.title
        return when (exam.examId) {
            "exam_1" -> if (exam.title == "1st Term Exam") "১ম সাময়িক পরীক্ষা" else exam.title
            "exam_2" -> if (exam.title == "2nd Term Exam") "২য় সাময়িক পরীক্ষা" else exam.title
            "exam_3" -> if (exam.title == "Final / Annual Exam") "বার্ষিক পরীক্ষা" else exam.title
            else -> exam.title
        }
    }

    fun localizeOutcome(outcomeName: String): String = when (outcomeName.uppercase()) {
        "PASS" -> resultPass
        "FAIL" -> resultFail
        else -> resultPending
    }

    fun localizePromotionStatus(status: String): String {
        if (language == AppLanguage.EN) return status
        return when (status) {
            "Promoted" -> statusPromoted
            "Not Promoted" -> statusNotPromoted
            "Studying" -> statusStudying
            "Passed Out" -> "উত্তীর্ণ (৫ম শ্রেণি সমাপ্ত)"
            "Transferred" -> "বদলি"
            else -> status
        }
    }
}

